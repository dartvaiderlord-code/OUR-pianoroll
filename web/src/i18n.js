const languageStorageKey = 'our-pianoroll-language';
let language = 'ru';
try {
  if (localStorage.getItem(languageStorageKey) === 'en') language = 'en';
} catch {}

function t(key, values = {}) {
  if (!key) return '';
  const text = translations[key]?.[language === 'en' ? 1 : 0] ?? key;
  return text.replace(/\{(\w+)\}/g,(_,name) => localize(values[name]));
}

const message = (key, values) => ({key,values});
function localize(value) {
  if (value && typeof value === 'object') return t(value.key,value.values);
  return String(value ?? '');
}

class LocalizedError extends Error {
  constructor(key) {
    super(t(key));
    this.localeMessage = message(key);
  }
}

const errorMessage = (error,fallback) => error instanceof LocalizedError ? error.localeMessage : message(fallback);

function translatePage() {
  document.documentElement.lang = language;
  const selector = '[data-i18n],[data-i18n-label],[data-i18n-title],[data-i18n-content]';
  for (const element of document.querySelectorAll(selector)) {
    const {i18n,i18nLabel,i18nTitle,i18nContent} = element.dataset;
    if (i18n) element.textContent = t(i18n);
    if (i18nLabel) element.setAttribute('aria-label',t(i18nLabel));
    if (i18nTitle) element.title = t(i18nTitle);
    if (i18nContent) element.setAttribute('content',t(i18nContent));
  }
}
